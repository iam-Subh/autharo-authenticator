//! The local database (PRD section 12.1).
//!
//! # Two files, not one
//!
//! Section 12.1: "The `meta` table holds the wrapped vault key and must stay
//! readable before the vault opens, so keep it in a small separate unencrypted
//! file, not inside the encrypted database."
//!
//! That is a bootstrapping constraint, not a preference. The key that opens
//! the encrypted database is itself stored wrapped in `meta`, so `meta` cannot
//! live inside the thing it unlocks. The split is expressed in the types:
//! [`MetaStore`] opens on its own, and [`Store`] cannot be constructed without
//! one, so no code path can reach the entries before the metadata.
//!
//! What each file holds:
//!
//! | File | Encrypted | Contents |
//! |---|---|---|
//! | `meta.db` | No | Wrapped vault key, device identifier, sync cursor, time offset |
//! | `vault.db` | By SQLCipher | `entry` and `outbox` |
//!
//! Nothing secret goes in `meta.db`. The wrapped vault key is ciphertext that
//! only the platform keystore can open, and the device identifier and cursor
//! are not secrets. Entry payloads are additionally encrypted per record
//! (section 9.3), so the SQLCipher layer protects the surrounding structure —
//! how many entries exist and when each changed — rather than their contents.

use core::fmt;

use rusqlite::{Connection, OptionalExtension, params};
// Keeps the linker from dropping the crate that compiles SQLite3 Multiple
// Ciphers. Nothing in this file calls into it directly — rusqlite does.
use sqlite3mc_sys as _;
use uuid::Uuid;

use crate::hlc::{Hlc, HlcParseError};

/// Schema version written to `PRAGMA user_version` in the vault file.
const VAULT_SCHEMA_VERSION: i64 = 1;
/// Schema version for the metadata file.
///
/// 2 added the `reconcile` table for section 10.4's deferred HOTP rule.
/// 3 replaced it: one row per entry could hold only one discarded candidate,
/// and section 10.4 step 4 requires every candidate to be kept.
const META_SCHEMA_VERSION: i64 = 3;

/// `meta` key holding the sync cursor, the highest server sequence seen.
const META_CURSOR: &str = "cursor";
/// `meta` key holding this device's 64-bit identifier (section 10.2).
const META_DEVICE_ID: &str = "device_id";
/// `meta` key holding the offset between device time and reference time (FR-38).
const META_TIME_OFFSET: &str = "time_offset_seconds";
/// `meta` keys holding the device slot (section 9.2.4).
const META_SLOT_WRAPPED: &str = "device_slot.wrapped_key";
const META_SLOT_NONCE: &str = "device_slot.nonce";
const META_SLOT_SCHEME: &str = "device_slot.scheme";

/// One encrypted record as stored on this device.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Record {
    /// UUIDv4, generated by the client that created the entry.
    pub id: String,
    /// The encrypted payload. Empty for a tombstone.
    pub ciphertext: Vec<u8>,
    /// The 24-byte XChaCha20-Poly1305 nonce. Empty for a tombstone.
    pub nonce: Vec<u8>,
    pub hlc: Hlc,
    pub deleted: bool,
    /// `None` until the server has accepted this version of the record.
    pub server_seq: Option<i64>,
    /// Local epoch milliseconds, for display only. Never used for ordering.
    pub updated_at: i64,
}

/// One entry waiting to be pushed to the server.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OutboxItem {
    pub entry_id: String,
    /// The HLC this device last saw the server hold, sent as the base revision
    /// so the server can detect a conflict.
    pub base_hlc: Option<Hlc>,
    pub attempts: u32,
    pub last_attempt: Option<i64>,
}

/// The vault key as it sits on disk: wrapped by the device slot (section 9.2.4).
///
/// `scheme` names how it was wrapped, so a device that later gains a PIN, or a
/// future release that changes the wrapping, can tell what it is looking at
/// instead of guessing from the length.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WrappedVaultKey {
    pub wrapped: Vec<u8>,
    pub nonce: Vec<u8>,
    pub scheme: String,
}

/// Anything that stops a database operation.
#[derive(Debug)]
pub enum StoreError {
    Database(rusqlite::Error),
    /// A stored HLC string that no longer parses, which means the file was
    /// edited outside the application.
    CorruptTimestamp(HlcParseError),
    /// The device slot in `meta` is present but incomplete.
    CorruptDeviceSlot {
        detail: String,
    },
    /// A caller asked to store a setting outside the range it permits.
    ///
    /// Refused rather than clamped. The one setting that uses this destroys
    /// the vault, and quietly storing the nearest legal value would arm
    /// something the caller did not ask for.
    InvalidValue {
        detail: String,
    },
}

impl fmt::Display for StoreError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Database(error) => write!(f, "The local database returned an error: {error}"),
            Self::CorruptTimestamp(error) => {
                write!(f, "The local database holds a damaged timestamp: {error}")
            }
            Self::CorruptDeviceSlot { detail } => write!(
                f,
                "This device's key record is damaged, so the vault cannot be opened: {detail}"
            ),
            Self::InvalidValue { detail } => write!(f, "That setting was refused: {detail}"),
        }
    }
}

impl std::error::Error for StoreError {}

impl From<rusqlite::Error> for StoreError {
    fn from(value: rusqlite::Error) -> Self {
        Self::Database(value)
    }
}

impl From<HlcParseError> for StoreError {
    fn from(value: HlcParseError) -> Self {
        Self::CorruptTimestamp(value)
    }
}

type Result<T> = core::result::Result<T, StoreError>;

/// The unencrypted metadata file.
///
/// Opens without a key, because it holds the wrapped key that everything else
/// needs. Keep it small and keep secrets out of it.
pub struct MetaStore {
    connection: Connection,
}

impl MetaStore {
    pub fn open(path: &str) -> Result<Self> {
        Self::from_connection(Connection::open(path)?)
    }

    pub fn open_in_memory() -> Result<Self> {
        Self::from_connection(Connection::open_in_memory()?)
    }

    fn from_connection(connection: Connection) -> Result<Self> {
        // Overwrite deleted or replaced cells inside SQLite pages. This does
        // not replace encryption, but it prevents old metadata values from
        // remaining readable in the database freelist.
        connection.pragma_update(None, "secure_delete", true)?;
        let store = Self { connection };
        store.migrate()?;
        Ok(store)
    }

    fn migrate(&self) -> Result<()> {
        let version: i64 = self
            .connection
            .query_row("PRAGMA user_version", [], |row| row.get(0))?;
        if version >= META_SCHEMA_VERSION {
            return Ok(());
        }

        if version < 1 {
            self.connection.execute_batch(
                "BEGIN;
                 CREATE TABLE IF NOT EXISTS meta (
                   key           TEXT PRIMARY KEY,
                   value         BLOB NOT NULL
                 );
                 PRAGMA user_version = 1;
                 COMMIT;",
            )?;
        }

        if version < 2 {
            // Section 10.4 step 2. The discarded ciphertext has to be kept,
            // not just the identifier: the winning record replaces the loser,
            // so without this the other counter no longer exists anywhere and
            // the reconcile step would have nothing to compare.
            //
            // It lives in the metadata file because the sync cycle writes it
            // while locked (OFF-09). Everything in it is ciphertext or an
            // identifier, so an unencrypted file is the right place.
            self.connection.execute_batch(
                "BEGIN;
                 CREATE TABLE IF NOT EXISTS reconcile (
                   entry_id      TEXT PRIMARY KEY,
                   ciphertext    BLOB NOT NULL,
                   nonce         BLOB NOT NULL,
                   recorded_at   INTEGER NOT NULL
                 );
                 PRAGMA user_version = 2;
                 COMMIT;",
            )?;
        }
        if version < 3 {
            // Section 10.4 step 4: "Keep every discarded candidate, not one
            // per entry." Version 2 keyed the table on `entry_id`, so a second
            // conflict before unlock had to either overwrite the first
            // candidate or be dropped. With three candidates, either choice
            // can lose the largest counter — and the reconcile then returns a
            // wrong value with nothing to signal it.
            //
            // Step 7 also needs the discarded record's HLC, which version 2
            // did not keep. Rows carried over from it have an empty `hlc`,
            // which the reconcile treats as unknown.
            let has_old: bool = self
                .connection
                .query_row(
                    "SELECT count(*) FROM sqlite_master
                      WHERE type = 'table' AND name = 'reconcile'",
                    [],
                    |row| row.get::<_, i64>(0),
                )
                .map(|count| count > 0)?;

            self.connection.execute_batch(
                "BEGIN;
                 CREATE TABLE IF NOT EXISTS reconcile_candidate (
                   id            INTEGER PRIMARY KEY AUTOINCREMENT,
                   entry_id      TEXT NOT NULL,
                   ciphertext    BLOB NOT NULL,
                   nonce         BLOB NOT NULL,
                   hlc           TEXT NOT NULL,
                   recorded_at   INTEGER NOT NULL
                 );
                 CREATE INDEX IF NOT EXISTS reconcile_candidate_entry_idx
                   ON reconcile_candidate (entry_id);
                 COMMIT;",
            )?;

            if has_old {
                self.connection.execute_batch(
                    "BEGIN;
                     INSERT INTO reconcile_candidate
                       (entry_id, ciphertext, nonce, hlc, recorded_at)
                     SELECT entry_id, ciphertext, nonce, '', recorded_at
                       FROM reconcile;
                     DROP TABLE reconcile;
                     COMMIT;",
                )?;
            }

            self.connection.execute_batch("PRAGMA user_version = 3;")?;
        }
        Ok(())
    }

    pub fn get(&self, key: &str) -> Result<Option<Vec<u8>>> {
        Ok(self
            .connection
            .query_row(
                "SELECT value FROM meta WHERE key = ?1",
                params![key],
                |row| row.get(0),
            )
            .optional()?)
    }

    pub fn set(&self, key: &str, value: &[u8]) -> Result<()> {
        self.connection.execute(
            "INSERT INTO meta (key, value) VALUES (?1, ?2)
             ON CONFLICT(key) DO UPDATE SET value = excluded.value",
            params![key, value],
        )?;
        Ok(())
    }

    pub fn remove(&self, key: &str) -> Result<()> {
        self.connection
            .execute("DELETE FROM meta WHERE key = ?1", params![key])?;
        Ok(())
    }

    /// Removes all installation metadata but keeps the database schema.
    ///
    /// A device wipe must remove account slots, sync cursors, UI settings, and
    /// lock policy data. Listing keys here would make every future metadata
    /// key a possible wipe omission.
    pub fn clear_all(&mut self) -> Result<()> {
        let transaction = self.connection.transaction()?;
        transaction.execute("DELETE FROM meta", [])?;
        transaction.execute("DELETE FROM reconcile_candidate", [])?;
        transaction.commit()?;
        Ok(())
    }

    /// The device slot, or `None` on a device that has never been set up.
    pub fn device_slot(&self) -> Result<Option<WrappedVaultKey>> {
        let Some(wrapped) = self.get(META_SLOT_WRAPPED)? else {
            return Ok(None);
        };
        let nonce = self
            .get(META_SLOT_NONCE)?
            .ok_or_else(|| StoreError::CorruptDeviceSlot {
                detail: "the wrapped key is present but its nonce is missing".to_string(),
            })?;
        let scheme = self
            .get(META_SLOT_SCHEME)?
            .and_then(|bytes| String::from_utf8(bytes).ok())
            .ok_or_else(|| StoreError::CorruptDeviceSlot {
                detail: "the wrapped key is present but its scheme is missing".to_string(),
            })?;

        Ok(Some(WrappedVaultKey {
            wrapped,
            nonce,
            scheme,
        }))
    }

    /// Writes the device slot. All three parts land together, so a crash
    /// cannot leave a wrapped key without the nonce that opens it.
    pub fn set_device_slot(&mut self, slot: &WrappedVaultKey) -> Result<()> {
        let transaction = self.connection.transaction()?;
        for (key, value) in [
            (META_SLOT_WRAPPED, slot.wrapped.as_slice()),
            (META_SLOT_NONCE, slot.nonce.as_slice()),
            (META_SLOT_SCHEME, slot.scheme.as_bytes()),
        ] {
            transaction.execute(
                "INSERT INTO meta (key, value) VALUES (?1, ?2)
                 ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                params![key, value],
            )?;
        }
        transaction.commit()?;
        Ok(())
    }

    /// Removes the device slot. The local vault becomes unopenable, which is
    /// the point: this is half of **Wipe this device** in section 9.2.4.
    pub fn clear_device_slot(&mut self) -> Result<()> {
        let transaction = self.connection.transaction()?;
        for key in [META_SLOT_WRAPPED, META_SLOT_NONCE, META_SLOT_SCHEME] {
            transaction.execute("DELETE FROM meta WHERE key = ?1", params![key])?;
        }
        transaction.commit()?;
        Ok(())
    }

    /// This device's identifier, generated on first use and never changed.
    pub fn device_id(&self) -> Result<u64> {
        if let Some(bytes) = self.get(META_DEVICE_ID)?
            && let Ok(bytes) = <[u8; 8]>::try_from(bytes.as_slice())
        {
            return Ok(u64::from_be_bytes(bytes));
        }
        let (high, _) = Uuid::new_v4().as_u64_pair();
        self.set(META_DEVICE_ID, &high.to_be_bytes())?;
        Ok(high)
    }

    /// The highest server sequence this device has applied.
    pub fn cursor(&self) -> Result<i64> {
        Ok(self
            .get(META_CURSOR)?
            .and_then(|bytes| String::from_utf8(bytes).ok())
            .and_then(|text| text.parse().ok())
            .unwrap_or(0))
    }

    pub fn set_cursor(&self, cursor: i64) -> Result<()> {
        self.set(META_CURSOR, cursor.to_string().as_bytes())
    }

    /// The stored offset between device time and reference time (FR-38).
    pub fn time_offset_seconds(&self) -> Result<i64> {
        Ok(self
            .get(META_TIME_OFFSET)?
            .and_then(|bytes| String::from_utf8(bytes).ok())
            .and_then(|text| text.parse().ok())
            .unwrap_or(0))
    }

    pub fn set_time_offset_seconds(&self, offset: i64) -> Result<()> {
        self.set(META_TIME_OFFSET, offset.to_string().as_bytes())
    }
}

/// The encrypted vault file, plus the metadata file it needs to open.
pub struct Store {
    vault: Connection,
    meta: MetaStore,
}

impl Store {
    /// Opens the vault at `path`.
    ///
    /// `sqlcipher_key` is the 64 hex character key from
    /// [`crate::crypto::VaultKey::sqlcipher_key`]. `None` opens the file
    /// unencrypted, which is only for the host tests — see the note in
    /// README.md about SQLCipher not yet being linked.
    pub fn open(path: &str, meta: MetaStore, sqlcipher_key: Option<&str>) -> Result<Self> {
        let vault = Connection::open(path)?;
        Self::from_connection(vault, meta, sqlcipher_key)
    }

    /// Opens a page-encrypted vault with a replacement key and, when needed,
    /// migrates an older key in place.
    ///
    /// The metadata is kept outside the connection attempt. This is required
    /// because a failed key check must not consume the only open metadata
    /// handle before the fallback key can be tried.
    pub fn open_with_key_migration(
        path: &str,
        meta: MetaStore,
        current_key: &str,
        previous_key: &str,
    ) -> Result<Self> {
        let current = Connection::open(path)?;
        match apply_encryption(&current, current_key) {
            Ok(()) => Self::from_keyed_connection(current, meta),
            Err(_) => {
                drop(current);
                let previous = Connection::open(path)?;
                apply_encryption(&previous, previous_key)?;
                rekey_connection(&previous, current_key)?;
                Self::from_keyed_connection(previous, meta)
            }
        }
    }

    pub fn open_in_memory(meta: MetaStore) -> Result<Self> {
        Self::from_connection(Connection::open_in_memory()?, meta, None)
    }

    fn from_connection(
        vault: Connection,
        meta: MetaStore,
        sqlcipher_key: Option<&str>,
    ) -> Result<Self> {
        if let Some(key) = sqlcipher_key {
            apply_encryption(&vault, key)?;
        }

        Self::from_keyed_connection(vault, meta)
    }

    fn from_keyed_connection(vault: Connection, meta: MetaStore) -> Result<Self> {
        // Foreign keys are off by default in SQLite, and the outbox references
        // the entry table.
        vault.pragma_update(None, "foreign_keys", true)?;
        vault.pragma_update(None, "secure_delete", true)?;

        let store = Self { vault, meta };
        store.migrate()?;
        Ok(store)
    }

    /// Applies the schema in section 12.1. Safe to call on every open.
    fn migrate(&self) -> Result<()> {
        let version: i64 = self
            .vault
            .query_row("PRAGMA user_version", [], |row| row.get(0))?;
        if version >= VAULT_SCHEMA_VERSION {
            return Ok(());
        }

        self.vault.execute_batch(
            "BEGIN;
             CREATE TABLE IF NOT EXISTS entry (
               id            TEXT PRIMARY KEY,
               ciphertext    BLOB NOT NULL,
               nonce         BLOB NOT NULL,
               hlc           TEXT NOT NULL,
               deleted       INTEGER NOT NULL DEFAULT 0,
               server_seq    INTEGER,
               updated_at    INTEGER NOT NULL
             );
             CREATE TABLE IF NOT EXISTS outbox (
               entry_id      TEXT PRIMARY KEY REFERENCES entry(id),
               base_hlc      TEXT,
               attempts      INTEGER NOT NULL DEFAULT 0,
               last_attempt  INTEGER
             );
             PRAGMA user_version = 1;
             COMMIT;",
        )?;
        Ok(())
    }

    /// The metadata file this vault was opened with.
    pub fn meta(&self) -> &MetaStore {
        &self.meta
    }

    pub fn meta_mut(&mut self) -> &mut MetaStore {
        &mut self.meta
    }

    /// Drops the vault connection and returns the metadata file.
    ///
    /// This is what a lock does (FR-31): the vault connection and the key that
    /// opened it go away, while the metadata file stays open so the next
    /// unlock can read the slot without reopening it.
    pub fn into_meta(self) -> MetaStore {
        self.meta
    }

    /// Writes a record this device changed, and queues it for the server in
    /// the same transaction (OFF-02).
    ///
    /// `base_hlc` is the HLC the server last confirmed for this entry, or
    /// `None` for an entry the server has never seen.
    pub fn write_local(&mut self, record: &Record, base_hlc: Option<Hlc>) -> Result<()> {
        let transaction = self.vault.transaction()?;
        upsert(&transaction, record)?;
        transaction.execute(
            "INSERT INTO outbox (entry_id, base_hlc, attempts, last_attempt)
             VALUES (?1, ?2, 0, NULL)
             ON CONFLICT(entry_id) DO UPDATE SET attempts = 0, last_attempt = NULL",
            params![record.id, base_hlc.map(|hlc| hlc.to_string())],
        )?;
        transaction.commit()?;
        Ok(())
    }

    /// Writes a record received from the server. This does not touch the
    /// outbox, because the server already holds this version.
    pub fn apply_remote(&mut self, record: &Record) -> Result<()> {
        upsert(&self.vault, record)?;
        Ok(())
    }

    pub fn get(&self, id: &str) -> Result<Option<Record>> {
        let record = self
            .vault
            .query_row(
                "SELECT id, ciphertext, nonce, hlc, deleted, server_seq, updated_at
                 FROM entry WHERE id = ?1",
                params![id],
                read_record,
            )
            .optional()?;
        record.transpose()
    }

    /// Every live record, newest first. Tombstones are excluded unless asked
    /// for, since the user interface never shows them.
    pub fn list(&self, include_deleted: bool) -> Result<Vec<Record>> {
        let mut statement = self.vault.prepare(
            "SELECT id, ciphertext, nonce, hlc, deleted, server_seq, updated_at
             FROM entry WHERE (?1 OR deleted = 0) ORDER BY hlc DESC",
        )?;
        let rows = statement.query_map(params![include_deleted], read_record)?;
        rows.collect::<rusqlite::Result<Vec<_>>>()?
            .into_iter()
            .collect()
    }

    /// Every entry's identifier and timestamp, tombstones included.
    ///
    /// [`Self::list`] carries the ciphertext with every row, which is most of
    /// the bytes and none of the answer when the caller only wants to know
    /// which version of what it holds. The convergence harness compares these
    /// across three devices before every cycle, and with the full rows the
    /// hundred-thousand-operation run went from seconds to not finishing.
    pub fn timestamps(&self) -> Result<Vec<(String, Hlc)>> {
        let mut statement = self.vault.prepare("SELECT id, hlc FROM entry")?;
        let rows = statement.query_map([], |row| {
            let id: String = row.get(0)?;
            let hlc: String = row.get(1)?;
            Ok((id, hlc))
        })?;

        let mut out = Vec::new();
        for row in rows {
            let (id, hlc) = row?;
            out.push((id, hlc.parse::<Hlc>()?));
        }
        Ok(out)
    }

    /// Marks a record deleted and drops its ciphertext (section 10.4).
    ///
    /// The row stays as a tombstone so that the delete can reach the other
    /// devices. Returns false when the entry is not present.
    pub fn tombstone(&mut self, id: &str, hlc: Hlc, updated_at: i64) -> Result<bool> {
        let Some(existing) = self.get(id)? else {
            return Ok(false);
        };
        let record = Record {
            id: id.to_string(),
            ciphertext: Vec::new(),
            nonce: Vec::new(),
            hlc,
            deleted: true,
            server_seq: None,
            updated_at,
        };
        self.write_local(&record, Some(existing.hlc))?;
        Ok(true)
    }

    /// Everything waiting to be pushed, oldest change first.
    pub fn outbox(&self) -> Result<Vec<OutboxItem>> {
        let mut statement = self.vault.prepare(
            "SELECT o.entry_id, o.base_hlc, o.attempts, o.last_attempt
             FROM outbox o JOIN entry e ON e.id = o.entry_id
             ORDER BY e.hlc ASC",
        )?;
        let rows = statement.query_map([], |row| {
            let base: Option<String> = row.get(1)?;
            Ok((
                OutboxItem {
                    entry_id: row.get(0)?,
                    base_hlc: None,
                    attempts: row.get::<_, i64>(2)? as u32,
                    last_attempt: row.get(3)?,
                },
                base,
            ))
        })?;

        let mut items = Vec::new();
        for row in rows {
            let (mut item, base) = row?;
            item.base_hlc = match base {
                Some(text) => Some(text.parse::<Hlc>()?),
                None => None,
            };
            items.push(item);
        }
        Ok(items)
    }

    /// Removes the entries the server accepted (step 7 of the sync cycle).
    pub fn outbox_clear(&mut self, entry_ids: &[String]) -> Result<()> {
        let transaction = self.vault.transaction()?;
        for id in entry_ids {
            transaction.execute("DELETE FROM outbox WHERE entry_id = ?1", params![id])?;
        }
        transaction.commit()?;
        Ok(())
    }

    /// Records a failed push, which drives the backoff in OFF-06.
    pub fn outbox_record_attempt(&self, entry_id: &str, at: i64) -> Result<()> {
        self.vault.execute(
            "UPDATE outbox SET attempts = attempts + 1, last_attempt = ?2 WHERE entry_id = ?1",
            params![entry_id, at],
        )?;
        Ok(())
    }

    /// Removes entries outright, with their outbox rows — no tombstone.
    ///
    /// Only for the full re-sync in section 10.6, and only for entries the
    /// server does not have and this device is not waiting to push. A row
    /// removed here leaves nothing behind, which is right for a record that
    /// exists only because this device's cursor went stale, and wrong for
    /// anything else: an entry the user deleted needs a tombstone, or the
    /// delete would not propagate.
    pub fn forget_entries(&mut self, ids: &[String]) -> Result<()> {
        let transaction = self.vault.transaction()?;
        for id in ids {
            transaction.execute("DELETE FROM outbox WHERE entry_id = ?1", params![id])?;
            transaction.execute("DELETE FROM entry WHERE id = ?1", params![id])?;
        }
        transaction.commit()?;
        Ok(())
    }

    /// Replaces every record in one transaction, outbox included.
    ///
    /// This throws away local work that has not reached the server. That is
    /// correct for **Wipe and re-download**, where the user has asked for the
    /// server's copy and nothing else, and wrong for the automatic re-sync in
    /// section 10.6 — see [`crate::sync::full_resync`], which keeps what is
    /// still waiting to be pushed.
    pub fn replace_all(&mut self, records: &[Record], cursor: i64) -> Result<()> {
        let transaction = self.vault.transaction()?;
        transaction.execute("DELETE FROM outbox", [])?;
        transaction.execute("DELETE FROM entry", [])?;
        for record in records {
            upsert(&transaction, record)?;
        }
        transaction.commit()?;
        self.meta.set_cursor(cursor)?;
        Ok(())
    }

    /// Deletes every entry and every outbox row, leaving the schema in place.
    ///
    /// Used by **Wipe this device** together with
    /// [`MetaStore::clear_device_slot`], and by the development-database wipe
    /// described in README.md.
    pub fn clear_entries(&mut self) -> Result<()> {
        let transaction = self.vault.transaction()?;
        transaction.execute("DELETE FROM outbox", [])?;
        transaction.execute("DELETE FROM entry", [])?;
        transaction.commit()?;
        Ok(())
    }

    // Convenience passthroughs, so callers holding a Store do not have to
    // reach through `meta()` for the things they use most.

    pub fn cursor(&self) -> Result<i64> {
        self.meta.cursor()
    }

    pub fn set_cursor(&self, cursor: i64) -> Result<()> {
        self.meta.set_cursor(cursor)
    }

    pub fn device_id(&self) -> Result<u64> {
        self.meta.device_id()
    }

    pub fn time_offset_seconds(&self) -> Result<i64> {
        self.meta.time_offset_seconds()
    }

    pub fn set_time_offset_seconds(&self, offset: i64) -> Result<()> {
        self.meta.set_time_offset_seconds(offset)
    }
}

fn rekey_connection(vault: &Connection, key: &str) -> Result<()> {
    if key.len() != 64 || !key.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return Err(StoreError::InvalidValue {
            detail: "the vault page key must contain 64 hexadecimal characters".to_string(),
        });
    }
    vault.execute_batch(&format!("PRAGMA hexrekey = '{key}';"))?;
    vault
        .query_row("SELECT count(*) FROM sqlite_master", [], |row| {
            row.get::<_, i64>(0)
        })
        .map_err(|_| {
            StoreError::Database(rusqlite::Error::InvalidPath(
                "the vault could not be read after page-key migration".into(),
            ))
        })?;
    Ok(())
}

/// Turns on page encryption for this connection (section 12.1).
///
/// # Every line here is load-bearing
///
/// SQLite3 Multiple Ciphers **opens an unencrypted database transparently**.
/// If the key is never applied, or applied wrongly, an old plaintext file
/// opens and every query works — so a test that checks the database opens
/// proves nothing at all. `core/tests/store.rs` asserts on the file's bytes
/// instead, which is section 12.1's first rule.
///
/// The order is fixed: cipher, then its parameters, then the key. SQLite3MC
/// reads the configuration when the key is supplied, so anything set after the
/// key is ignored — silently.
fn apply_encryption(vault: &Connection, key: &str) -> Result<()> {
    // Section 12.1 rule 2: name the cipher, do not accept the default. This
    // library's default has changed between releases, and a changed default
    // makes an existing database unopenable — the file is still encrypted, and
    // nothing on the device can read it. ChaCha20-Poly1305 also matches the
    // record layer, so one primitive covers both.
    vault.execute_batch("PRAGMA cipher = 'chacha20';")?;

    // Rule 2 again: pin the iteration count. It is unused while the key is
    // supplied raw below, because a uniformly random 256-bit key needs no
    // stretching — but pinning it means a future switch to a passphrase
    // inherits a stated cost rather than whatever the release defaults to.
    vault.execute_batch("PRAGMA kdf_iter = 64007;")?;

    // Rule 3, belt to the compile-time SQLITE_TEMP_STORE=3 brace. Temporary
    // tables and sort spills would otherwise write plaintext pages next to the
    // encrypted file.
    vault.execute_batch("PRAGMA temp_store = MEMORY;")?;

    // `hexkey` takes the key as it is. `key` would treat it as a passphrase
    // and run it through the KDF, which would derive a different key and leave
    // every existing database unopenable.
    vault.execute_batch(&format!("PRAGMA hexkey = '{key}';"))?;

    // Proof that the key took. Reading the schema forces SQLite to decrypt
    // page one; a wrong key fails here rather than at the first query, and an
    // unkeyed open of an encrypted file fails here too.
    vault
        .query_row("SELECT count(*) FROM sqlite_master", [], |row| {
            row.get::<_, i64>(0)
        })
        .map_err(|_| {
            StoreError::Database(rusqlite::Error::InvalidPath(
                "the vault could not be decrypted with this key".into(),
            ))
        })?;

    Ok(())
}

fn upsert(connection: &Connection, record: &Record) -> rusqlite::Result<()> {
    connection.execute(
        "INSERT INTO entry (id, ciphertext, nonce, hlc, deleted, server_seq, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)
         ON CONFLICT(id) DO UPDATE SET
           ciphertext = excluded.ciphertext,
           nonce      = excluded.nonce,
           hlc        = excluded.hlc,
           deleted    = excluded.deleted,
           server_seq = excluded.server_seq,
           updated_at = excluded.updated_at",
        params![
            record.id,
            record.ciphertext,
            record.nonce,
            record.hlc.to_string(),
            record.deleted,
            record.server_seq,
            record.updated_at,
        ],
    )?;
    Ok(())
}

/// Reads one row. The HLC is parsed outside the closure because rusqlite's row
/// mapper cannot carry this crate's error type.
fn read_record(row: &rusqlite::Row<'_>) -> rusqlite::Result<Result<Record>> {
    let hlc: String = row.get(3)?;
    Ok((|| {
        Ok(Record {
            id: row.get(0)?,
            ciphertext: row.get(1)?,
            nonce: row.get(2)?,
            hlc: hlc.parse::<Hlc>()?,
            deleted: row.get(4)?,
            server_seq: row.get(5)?,
            updated_at: row.get(6)?,
        })
    })())
}

