/// Deletes an unencrypted vault file (PRD section 12.1 rule 4).
///
/// Two earlier shapes need discarding, and one check covers both. Stage S2
/// kept `meta`, `entry`, and `outbox` in one unencrypted file with payloads
/// written in the clear. Stage S3 split the files and encrypted the payloads
/// but had no page-encrypting library, so `vault.db` was still a plain SQLite
/// file. Neither opens under a key now, and neither should.
///
/// # Why the header, and not the schema
///
/// An earlier version of this function looked for a `meta` table, which only
/// recognised the S2 shape. The file header recognises both and anything else
/// that is not encrypted: a plain SQLite database begins with the ASCII bytes
/// `SQLite format 3`, and an encrypted one does not, because the header is
/// encrypted with everything else.
///
/// # Why discard rather than migrate
///
/// Section 12.1 rule 4. Nothing has shipped, so there is no user data to
/// preserve — and a copy-and-delete migration would read every plaintext
/// secret and rewrite it, leaving the old pages on flash. Wear levelling means
/// their removal cannot be proved, so the honest options are "delete the file"
/// or "leave plaintext somewhere unprovable". Returns true when something was
/// deleted.
pub fn discard_unencrypted_vault(vault_path: &str, meta_path: &str) -> Result<bool> {
    use std::io::Read;

    let path = std::path::Path::new(vault_path);
    if !path.exists() {
        return Ok(false);
    }

    // Only the first 16 bytes are needed, so a large vault is not read in.
    let mut header = [0u8; 15];
    {
        let mut file = std::fs::File::open(path).map_err(open_failed(vault_path))?;
        match file.read_exact(&mut header) {
            Ok(()) => {}
            // A file too short to hold a header is not a database. An empty
            // file is what an interrupted first run leaves, and SQLite is
            // happy to initialise it, so it is left alone.
            Err(_) => return Ok(false),
        }
    }

    if &header != b"SQLite format 3" {
        return Ok(false); // Encrypted, and therefore current.
    }

    std::fs::remove_file(path).map_err(open_failed(vault_path))?;
    // Journal and write-ahead files hold copies of the same plaintext pages.
    for suffix in ["-journal", "-wal", "-shm"] {
        std::fs::remove_file(format!("{vault_path}{suffix}")).ok();
    }
    // Any metadata file beside it belongs to a vault that no longer exists.
    // Keeping it would leave a device slot whose key opens nothing.
    std::fs::remove_file(meta_path).ok();

    Ok(true)
}

fn open_failed(path: &str) -> impl Fn(std::io::Error) -> StoreError + '_ {
    move |error| {
        StoreError::Database(rusqlite::Error::InvalidPath(
            format!("{path}: {error}").into(),
        ))
    }
}

/// `meta` key counting consecutive failed unlocks (FR-35).
const META_FAILED_UNLOCKS: &str = "device_slot.failed_unlocks";

impl MetaStore {
    /// How many unlocks have failed in a row.
    ///
    /// Kept in the unencrypted metadata file on purpose: it has to be readable
    /// and writable while the vault is shut, which is exactly when it matters.
    /// Someone who can edit that file can reset the counter — but they could
    /// equally copy the file, so the counter was never what stood between them
    /// and the vault. It bounds guessing by a person holding the phone, which
    /// is the case FR-35 is about.
    pub fn failed_unlocks(&self) -> Result<u32> {
        Ok(self
            .get(META_FAILED_UNLOCKS)?
            .and_then(|bytes| String::from_utf8(bytes).ok())
            .and_then(|text| text.parse().ok())
            .unwrap_or(0))
    }

    /// Records a failed unlock and returns the new total.
    pub fn record_failed_unlock(&self) -> Result<u32> {
        let next = self.failed_unlocks()?.saturating_add(1);
        self.set(META_FAILED_UNLOCKS, next.to_string().as_bytes())?;
        Ok(next)
    }

    /// Clears the counter. Called on every successful unlock, so the limit
    /// applies to consecutive failures rather than to failures for all time.
    pub fn clear_failed_unlocks(&self) -> Result<()> {
        self.remove(META_FAILED_UNLOCKS)
    }
}

/// One discarded candidate from a conflict resolved without reading the
/// counters (section 10.4).
///
/// Holds a record the HLC rule threw away. An entry may have several: each
/// conflict before the next unlock adds one, and step 4 requires every one to
/// be kept, because any of them could hold the largest counter.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ReconcileCandidate {
    /// Row identifier. The table is keyed on this rather than on the entry, so
    /// one entry can hold several candidates.
    pub id: i64,
    pub entry_id: String,
    /// The discarded ciphertext. Opaque to the code that writes it.
    pub ciphertext: Vec<u8>,
    pub nonce: Vec<u8>,
    /// The HLC the discarded record carried. Step 7 derives the corrected
    /// timestamp from these rather than from a clock.
    ///
    /// `None` only for rows carried over from schema version 2, which did not
    /// keep it.
    pub hlc: Option<Hlc>,
    pub recorded_at: i64,
}

impl MetaStore {
    fn insert_candidate(
        &self,
        entry_id: &str,
        ciphertext: &[u8],
        nonce: &[u8],
        hlc: Hlc,
        at: i64,
    ) -> Result<()> {
        // Always an insert. Section 10.4 step 4: an entry may hold several
        // candidates, and dropping or overwriting one can lose the largest
        // counter.
        self.connection.execute(
            "INSERT INTO reconcile_candidate
               (entry_id, ciphertext, nonce, hlc, recorded_at)
             VALUES (?1, ?2, ?3, ?4, ?5)",
            params![entry_id, ciphertext, nonce, hlc.to_string(), at],
        )?;
        Ok(())
    }

    fn list_candidates(&self) -> Result<Vec<ReconcileCandidate>> {
        let mut statement = self.connection.prepare(
            "SELECT id, entry_id, ciphertext, nonce, hlc, recorded_at
               FROM reconcile_candidate ORDER BY entry_id, id",
        )?;
        let rows = statement.query_map([], |row| {
            let hlc: String = row.get(4)?;
            Ok((
                ReconcileCandidate {
                    id: row.get(0)?,
                    entry_id: row.get(1)?,
                    ciphertext: row.get(2)?,
                    nonce: row.get(3)?,
                    hlc: None,
                    recorded_at: row.get(5)?,
                },
                hlc,
            ))
        })?;

        let mut candidates = Vec::new();
        for row in rows {
            let (mut candidate, hlc) = row?;
            // An empty string is a version 2 row, which kept no timestamp.
            candidate.hlc = hlc.parse::<Hlc>().ok();
            candidates.push(candidate);
        }
        Ok(candidates)
    }

    fn delete_candidates(&self, entry_id: &str) -> Result<()> {
        self.connection.execute(
            "DELETE FROM reconcile_candidate WHERE entry_id = ?1",
            params![entry_id],
        )?;
        Ok(())
    }

    fn count_candidates(&self) -> Result<usize> {
        let count: i64 =
            self.connection
                .query_row("SELECT count(*) FROM reconcile_candidate", [], |row| {
                    row.get(0)
                })?;
        Ok(count as usize)
    }

    fn has_candidates(&self, entry_id: &str) -> Result<bool> {
        let count: i64 = self.connection.query_row(
            "SELECT count(*) FROM reconcile_candidate WHERE entry_id = ?1",
            params![entry_id],
            |row| row.get(0),
        )?;
        Ok(count > 0)
    }
}

impl Store {
    /// Records a discarded candidate (section 10.4 steps 2 and 3).
    ///
    /// Called by the sync cycle, which may be locked, so nothing here reads a
    /// payload. Both directions are recorded: when the remote wins the local
    /// record is discarded, and when the local wins the remote one is —
    /// because the counter rule takes the larger value regardless of which HLC
    /// was higher.
    pub fn record_reconcile(
        &self,
        entry_id: &str,
        discarded_ciphertext: &[u8],
        discarded_nonce: &[u8],
        discarded_hlc: Hlc,
        at: i64,
    ) -> Result<()> {
        if discarded_ciphertext.is_empty() {
            // A tombstone has no payload and no counter to compare.
            return Ok(());
        }
        self.meta.insert_candidate(
            entry_id,
            discarded_ciphertext,
            discarded_nonce,
            discarded_hlc,
            at,
        )
    }

    /// Every pending candidate, grouped by entry and oldest first within each.
    pub fn reconcile_pending(&self) -> Result<Vec<ReconcileCandidate>> {
        self.meta.list_candidates()
    }

    /// How many candidates are waiting, without reading any of them.
    ///
    /// [`Self::reconcile_pending`] loads every discarded ciphertext, which the
    /// reconcile needs and a caller asking "is there anything to do" does not.
    pub fn reconcile_pending_count(&self) -> Result<usize> {
        self.meta.count_candidates()
    }

    /// Section 10.4 step 5: whether this entry may produce a code yet.
    ///
    /// An entry with a candidate outstanding may be holding the smaller
    /// counter, and a code from a counter behind the issuer's is one the
    /// issuer has already rejected. Refusing beats being confidently wrong.
    pub fn reconcile_pending_for(&self, entry_id: &str) -> Result<bool> {
        self.meta.has_candidates(entry_id)
    }

    /// Section 10.4 step 9: cleared only once the correction is written.
    pub fn clear_reconcile(&self, entry_id: &str) -> Result<()> {
        self.meta.delete_candidates(entry_id)
    }
}
